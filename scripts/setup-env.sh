#!/bin/sh
# Once before the first start, harmless again: .env from .env.example when there is none (0600), a generated
# POSTGRES_PASSWORD (the database's superuser), POSTGRES_APP_PASSWORD (the app's own role cobe_news_app, 0.1.22 on) and
# POSTGRES_RESTORE_PASSWORD (the restore test's own role cobe_news_restore) when it has none. The passwords never go into the repository (.env is ignored by Git).
# Keep POSTGRES_PASSWORD: the database volume (db18) was created with it (docs/BETRIEB.md).
set -eu
cd "$(dirname "$0")/.."
umask 077
if [ ! -f .env ]; then
  cp .env.example .env
  echo ".env created from .env.example"
fi
chmod 600 .env
if ! grep -Eq '^POSTGRES_PASSWORD=.+' .env; then
  pw=$(LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 40)  # letters and digits: nothing to quote in a URL or shell
  printf '\n# PostgreSQL password – generated by scripts/setup-env.sh; keep it (the database volume was created with it)\nPOSTGRES_PASSWORD=%s\n' "$pw" >>.env
  echo "POSTGRES_PASSWORD generated in .env"
else
  echo "POSTGRES_PASSWORD already set in .env – unchanged"
fi
if ! grep -Eq '^POSTGRES_APP_PASSWORD=.+' .env; then
  pw=$(LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 40)
  printf '\n# password of the app'"'"'s database role cobe_news_app (no superuser) – generated by scripts/setup-env.sh; the database sets it at every start\nPOSTGRES_APP_PASSWORD=%s\n' "$pw" >>.env
  echo "POSTGRES_APP_PASSWORD generated in .env"
else
  echo "POSTGRES_APP_PASSWORD already set in .env – unchanged"
fi
if ! grep -Eq '^POSTGRES_RESTORE_PASSWORD=' .env; then
  pw=$(LC_ALL=C tr -dc 'A-Za-z0-9' </dev/urandom | head -c 40)
  printf '\n# password of the restore test'"'"'s role cobe_news_restore (its own throwaway database only) – generated by scripts/setup-env.sh;\n# the database sets it up at every start. Empty: no restore test (docs/BETRIEB.md: Rücksicherungs-Test)\nPOSTGRES_RESTORE_PASSWORD=%s\n' "$pw" >>.env
  echo "POSTGRES_RESTORE_PASSWORD generated in .env"
else
  echo "POSTGRES_RESTORE_PASSWORD already in .env – unchanged"
fi
