/** The icons a category of the catalogue data may name (backend/app/catalog/categories.yaml; the backend's ICONS list
 *  must match – a test compares them). A fixed map: only these icons end up in the bundle. */
const CATALOG_ICONS: Record<string, LucideIcon> = {
  activity: Activity,
  "app-window": AppWindow,
  "archive-restore": ArchiveRestore,
  "brick-wall": BrickWall,
  briefcase: Briefcase,
  cloud: Cloud,
  code: Code,
  container: Container,
  database: Database,
  factory: Factory,
  "file-badge": FileBadge,
  globe: Globe,
  "hard-drive": HardDrive,
  "key-round": KeyRound,
  laptop: Laptop,
  layers: Layers,
  "lock-keyhole": LockKeyhole,
  mail: Mail,
  "monitor-smartphone": MonitorSmartphone,
  network: Network,
  package: Package,
  printer: Printer,
  "scan-search": ScanSearch,
  "scroll-text": ScrollText,
  server: Server,
  shield: Shield,
  split: Split,
  terminal: Terminal,
  ticket: Ticket,
  users: Users,
}

export function CategoryIcon({ icon, className }: { icon: string | undefined; className?: string }) {
  const Icon = (icon && CATALOG_ICONS[icon]) || Package
  return <Icon className={className} aria-hidden />
}
